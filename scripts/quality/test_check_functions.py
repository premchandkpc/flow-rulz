"""Regression coverage for length boundaries across repository languages."""

import unittest

from check_functions import scan_source

FUNCTION_SOURCES = {
    "go": ("package sample\nfunc work() {\n", "    // line\n", "}\n"),
    "rust": ("fn work() {\n", "    // line\n", "}\n"),
    "python": ("def work():\n", "    # line\n", "    pass\n"),
    "bash": ("work() {\n", "    # line\n", "}\n"),
    "typescript": ("function work(): void {\n", "    // line\n", "}\n"),
    "tsx": ("function Work() {\n", "    // line\n", "return <div />; }\n"),
    "javascript": ("function work() {\n", "    // line\n", "}\n"),
    "java": ("class Sample {\nvoid work() {\n", "    // line\n", "}\n}\n"),
}
CLOSURE_SOURCES = {
    "go": ("package sample\nvar f = func() {\n", "    // line\n", "}\n"),
    "rust": ("fn work() { let f = || {\n", "    // line\n", "}; }\n"),
    "typescript": ("const f = () => {\n", "    // line\n", "};\n"),
    "javascript": ("const f = () => {\n", "    // line\n", "};\n"),
}


def fixture(source, lines):
    start, body, end = source
    return (start + body * (lines - 2) + end).encode()


class FunctionLengthTests(unittest.TestCase):
    def test_fifteen_lines_are_allowed(self):
        for language, source in FUNCTION_SOURCES.items():
            with self.subTest(language=language):
                self.assertEqual(scan_source(fixture(source, 15), language, "sample"), [])

    def test_sixteen_lines_are_rejected(self):
        for language, source in FUNCTION_SOURCES.items():
            with self.subTest(language=language):
                violations = scan_source(fixture(source, 16), language, "sample")
                self.assertEqual(len(violations), 1)
                self.assertEqual(violations[0]["lines"], 16)

    def test_closures_are_not_exempt(self):
        for language, source in CLOSURE_SOURCES.items():
            with self.subTest(language=language):
                violations = scan_source(fixture(source, 16), language, "sample")
                self.assertTrue(violations)
                self.assertTrue(all(item["lines"] == 16 for item in violations))

    def test_generated_and_test_files_are_not_exempt(self):
        source = b"// Code generated by a tool. DO NOT EDIT.\n" + fixture(FUNCTION_SOURCES["go"], 16)
        for path in ("generated.go", "sample_test.go"):
            self.assertEqual(len(scan_source(source, "go", path)), 1)

    def test_strings_do_not_create_functions(self):
        source = b'package sample\nconst text = `func fake() {\n' + b'// line\n' * 20 + b'}`\n'
        self.assertEqual(scan_source(source, "go", "sample.go"), [])

    def test_blank_lines_and_multiline_signatures_count(self):
        source = b'package sample\nfunc work(\n) {\n' + b'\n' * 13 + b'}\n'
        violations = scan_source(source, "go", "sample.go")
        self.assertEqual(violations[0]["lines"], 16)


if __name__ == "__main__":
    unittest.main()
